import { existsSync, readFileSync, readdirSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateKatexFontNotices } from './katex-font-notices.mjs';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const fallbackLicenses = new Map([
  ['@uiw/react-codemirror@4.25.12', 'uiw-react-codemirror-4.25.12.LICENSE'],
  ['@uiw/codemirror-extensions-basic-setup@4.25.12', 'uiw-react-codemirror-4.25.12.LICENSE'],
]);

function locatePackage(name, from) {
  let current = from;
  while (true) {
    const candidate = path.join(current, 'node_modules', name);
    if (existsSync(path.join(candidate, 'package.json'))) return realpathSync(candidate);
    const parent = path.dirname(current);
    if (parent === current) return undefined;
    current = parent;
  }
}

function licenseFiles(directory, prefix = '') {
  return readdirSync(directory).flatMap((name) => {
    if (!prefix && !/^(licen[cs]e|copying|notice)(?:[.-]|$)/i.test(name)) return [];
    const filename = path.join(directory, name);
    return statSync(filename).isDirectory()
      ? licenseFiles(filename, `${prefix}${name}/`)
      : [{ name: `${prefix}${name}`, text: readFileSync(filename, 'utf8').trim() }];
  });
}

function packageLicenses(directory, manifest) {
  const files = licenseFiles(directory);
  if (manifest.name === 'katex') {
    files.push({ name: 'Font licenses (SIL OFL 1.1)', text: generateKatexFontNotices(directory) });
  }
  if (files.length) return files;
  // Some packages publish the full license only in their README.
  for (const filename of readdirSync(directory).filter((name) => /^readme(?:\.|$)/i.test(name))) {
    const readme = readFileSync(path.join(directory, filename), 'utf8');
    const license = readme.match(/^#{1,6}\s+Licen[cs]e[^\n]*\n([\s\S]*?)(?=^#{1,6}\s|$(?![\s\S]))/im)?.[1]?.trim();
    if (license?.includes('Permission is hereby granted') && license.includes('THE SOFTWARE IS PROVIDED')) {
      return [{ name: `${filename} (License section)`, text: license }];
    }
  }
  const fallback = fallbackLicenses.get(`${manifest.name}@${manifest.version}`);
  if (fallback) {
    return [{
      name: 'LICENSE (upstream v4.25.12; npm archive omits it)',
      text: readFileSync(new URL(`./licenses/${fallback}`, import.meta.url), 'utf8').trim(),
    }];
  }
  throw new Error(`Missing complete license text for ${manifest.name}@${manifest.version}; verify upstream before release.`);
}

export function generateNotices(root = projectRoot, outDir) {
  const lock = readFileSync(path.join(root, 'pnpm-lock.yaml'), 'utf8');
  const manifest = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
  const packages = new Map();
  const visited = new Set();

  function visit(name, from, optional = false) {
    const directory = locatePackage(name, from);
    if (!directory) {
      if (optional) return;
      throw new Error(`Dependency ${name} is missing; run pnpm install --frozen-lockfile.`);
    }
    if (visited.has(directory)) return;
    visited.add(directory);
    const pkg = JSON.parse(readFileSync(path.join(directory, 'package.json'), 'utf8'));
    const key = `${pkg.name}@${pkg.version}`;
    if (!lock.includes(`${key}:`) && !lock.includes(`${key}':`) && !lock.includes(`${key}":`)) {
      throw new Error(`${key} is not in pnpm-lock.yaml; install the locked dependencies before release.`);
    }
    packages.set(key, { pkg, files: packageLicenses(directory, pkg) });
    for (const dependency of Object.keys(pkg.dependencies || {})) visit(dependency, directory);
    for (const dependency of Object.keys(pkg.optionalDependencies || {})) visit(dependency, directory, true);
    for (const dependency of Object.keys(pkg.peerDependencies || {})) {
      visit(dependency, directory, pkg.peerDependenciesMeta?.[dependency]?.optional === true);
    }
  }
  for (const dependency of Object.keys(manifest.dependencies || {})) visit(dependency, root);

  const sections = [...packages.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([key, { pkg, files }]) => {
    const source = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
    return [
      `## ${key}`,
      `Declared license: ${pkg.license || 'see license text below'}`,
      source ? `Source: ${source}` : '',
      ...files.map((file) => `### ${file.name}\n\n${file.text}`),
    ].filter(Boolean).join('\n\n');
  });
  const output = [
    '# Third-party notices',
    'Generated by `pnpm licenses:generate` from installed runtime dependencies and their dependencies/peers, verified against pnpm-lock.yaml. This includes dependencies that tree shaking may exclude. The build ships this file unchanged. Licenses apply to the named third-party packages, not to EasyMD original code.',
    'The two @uiw packages omit LICENSE in their npm archives. Their complete license is vendored from https://raw.githubusercontent.com/uiwjs/react-codemirror/v4.25.12/LICENSE. A package version without a verified full license makes generation fail.',
    `Packages: ${packages.size}.`,
    ...sections,
    '',
  ].join('\n\n');
  writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), output);
  if (outDir) writeFileSync(path.join(outDir, 'THIRD_PARTY_NOTICES.md'), output);
  return packages.size;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`Generated notices for ${generateNotices()} runtime dependency packages.`);
}
